const Ctx = createContext<{ lang: Lang; setLang: (lang: Lang) => void; t: (value: Localized) => string }>({
  lang: "kk", setLang: () => undefined, t: (value) => value.kk,
});

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>("kk");
  return <Ctx.Provider value={{ lang, setLang, t: (value) => value[lang] }}>{children}</Ctx.Provider>;
}

export const useLang = () => useContext(Ctx);